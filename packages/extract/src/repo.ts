import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, statSync } from "node:fs";
import { basename, extname, join } from "node:path";
import type { FileFact, FileKind } from "./types.ts";

const CODE_LANGS: Record<string, string> = {
  ".ts": "ts", ".tsx": "tsx", ".mts": "ts", ".cts": "ts",
  ".js": "js", ".jsx": "jsx", ".mjs": "js", ".cjs": "js",
  ".vue": "vue", ".svelte": "svelte", ".py": "python", ".go": "go",
};
const TEXT_EXTS = new Set([".md", ".mdx", ".json", ".yaml", ".yml", ".toml", ".html", ".css", ".scss", ".txt", ".env.example"]);
const AGENT_NAMES = new Set(["CLAUDE.md", "AGENTS.md", "GEMINI.md", ".cursorrules"]);
const AGENT_DIRS = [".wolf/", ".claude/", ".cursor/", ".codex/", ".agents/"];
const MAX_BYTES = 1_000_000;

export function git(root: string, args: string[]): string {
  // stderr is captured into the thrown error, not printed: a repo with no commits yet is normal.
  return execFileSync("git", ["-C", root, ...args], { encoding: "utf8", maxBuffer: 256 * 1024 * 1024, stdio: ["ignore", "pipe", "pipe"] });
}

export function isGitRepo(root: string): boolean {
  try {
    git(root, ["rev-parse", "--is-inside-work-tree"]);
    return true;
  } catch {
    return false;
  }
}

export const isTestPath = (path: string) =>
  /(^|\/)(__tests__|tests?)\//.test(path) || /\.(test|spec)\.[cm]?[jt]sx?$/.test(path);

export function classify(path: string, head: string): FileKind {
  const name = basename(path);
  const ext = extname(path);
  if (AGENT_NAMES.has(name) || AGENT_DIRS.some((dir) => path.startsWith(dir))) return "agent";
  if (ext === ".md" || ext === ".mdx") return "doc";
  if (name === "package.json" || /^tsconfig.*\.json$/.test(name) || /\.config\.[cm]?[jt]s$/.test(name) ||
    /^\.?(eslint|prettier|stylelint)/.test(name) || name === "vite-env.d.ts") return "config";
  if (CODE_LANGS[ext]) {
    if (isTestPath(path)) return "test";
    if (/(^|\/)(generated|__generated__)\//.test(path) || /\bauto-?generated\b|\bgenerated by\b|do not edit/i.test(head)) {
      return "generated";
    }
    return "source";
  }
  return "other";
}

/** Build output and bundles: machine-made copies of the source that would swamp the call graph. */
const BUILD_OUTPUT = /(^|\/)(dist|build|\.next|\.output|\.svelte-kit|coverage)\/|\.(min|bundle)\.[cm]?js$/;

/** Tracked plus untracked-but-not-ignored files, as git sees them, minus build output. Never writes to the repo. */
export function listFiles(root: string): FileFact[] {
  const out = git(root, ["ls-files", "-co", "--exclude-standard", "-z"]);
  const files: FileFact[] = [];
  for (const path of out.split("\0").filter(Boolean)) {
    const ext = extname(path);
    if (!CODE_LANGS[ext] && !TEXT_EXTS.has(ext) && !AGENT_NAMES.has(basename(path))) continue;
    if (BUILD_OUTPUT.test(path)) continue;
    let size: number;
    try {
      size = statSync(join(root, path)).size;
    } catch {
      continue; // listed but deleted in the working tree
    }
    if (size > MAX_BYTES) continue;
    const text = readFileSync(join(root, path), "utf8");
    files.push({
      path,
      kind: classify(path, text.slice(0, 400)),
      lang: CODE_LANGS[ext] ?? null,
      lines: text.length === 0 ? 0 : text.split("\n").length - (text.endsWith("\n") ? 1 : 0),
      hash: createHash("sha1").update(text).digest("hex").slice(0, 12),
    });
  }
  return files.sort((a, b) => a.path.localeCompare(b.path));
}
